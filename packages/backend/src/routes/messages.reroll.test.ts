import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import express from 'express';
const root = mkdtempSync(join(tmpdir(), 'reroll-http-'));
process.env.RESONANT_HOME = root;
writeFileSync(join(root, 'config.yaml'), 'agent:\n  cwd: .\n  model: claude-sonnet-4-6\n');
const {initDb, createMessage, getMessage} = await import('../services/db.js');
const {default: router} = await import('./messages.js');
const db = initDb(join(root, 'test.db'));
db.prepare("INSERT INTO threads (id,name,type,created_at,last_activity_at) VALUES ('a','test','named',?,?)").run(new Date().toISOString(),new Date().toISOString());
const add = (id: string, role: 'user'|'companion') => createMessage({id,threadId:'a',role,content:id,createdAt:new Date().toISOString()});
const app = express(); app.use(express.json()); app.use('/api',router);
const calls: unknown[][] = [];
const server = app.listen(0,'127.0.0.1');
await new Promise<void>(resolve => server.once('listening',resolve));
const base = `http://127.0.0.1:${(server.address() as {port:number}).port}/api/messages`;
after(async () => { await new Promise<void>(resolve => server.close(()=>resolve())); db.close(); rmSync(root,{recursive:true,force:true}); });
test('HTTP preview, absent engine, required confirmation, stale count, one dispatch and edit notice', async () => {
 add('u','user'); add('c','companion');
 const p = await (await fetch(`${base}/c/regenerate-preview`)).json() as {count:number;revision:string};
 assert.equal(p.count,1); assert.equal(getMessage('c')?.deleted_at,null);
 const post = (body: unknown) => fetch(`${base}/c/regenerate`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
 assert.equal((await post(p)).status,503); assert.equal(getMessage('c')?.deleted_at,null);
 app.locals.agentService = {processMessage: async (...args: unknown[]) => { calls.push(args); return ''; }};
 assert.equal((await post({})).status,409);
 add('tail','user'); assert.equal((await post(p)).status,409);
 const fresh = await (await fetch(`${base}/c/regenerate-preview`)).json();
 assert.equal((await post(fresh)).status,200); assert.equal(calls.length,1);
 assert.equal(calls[0][1],'u'); assert.match((calls[0][3] as {withdrawn:string}).withdrawn,/no longer on their screen/);
 assert.equal((await post(fresh)).status,400); assert.equal(calls.length,1);
 const edit = await fetch(`${base}/u`,{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({content:'edited',rerun:true})});
 assert.equal(edit.status,200); assert.equal(calls.length,2);
 assert.match((calls[1][3] as {withdrawn:string}).withdrawn,/Earlier wording/);
 assert.equal(calls[1][1],'edited');
});
